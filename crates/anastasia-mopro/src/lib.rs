// Here we're calling a macro exported with Uniffi. This macro will
// write some functions and bind them to FFI type.
// These functions include:
// - `generate_circom_proof`
// - `verify_circom_proof`
// - `generate_halo2_proof`
// - `verify_halo2_proof`
// - `generate_noir_proof`
// - `verify_noir_proof`
mopro_ffi::app!();

mod ffi_types;

use crate::ffi_types::{CircuitMeta, CommitResult, ProofResult};

#[uniffi::export]
fn commit_attrs(
    subject: Vec<u8>,
    subject_key_identifier: Vec<u8>,
    subject_pk_x: Vec<u8>,
    subject_pk_y: Vec<u8>,
    r: Option<String>,
) -> Result<CommitResult, MoproError> {
    let result = anastasia_rs::commit_attrs(
        &subject,
        &subject_key_identifier,
        &subject_pk_x,
        &subject_pk_y,
        r.as_deref(),
    )
    .map_err(|e| MoproError::NoirError(e.to_string()))?;
    Ok(result.into())
}

#[uniffi::export]
fn prove(
    circuit_meta: CircuitMeta,
    cert: Vec<u8>,
    authority_key_id: Vec<u8>,
    issuer_pk_x: Vec<u8>,
    issuer_pk_y: Vec<u8>,
    prev_cmt_x: String,
    prev_cmt_y: String,
    prev_cmt_r: String,
    now: Option<i64>,
) -> Result<ProofResult, MoproError> {
    let proof = anastasia_rs::prove(
        &circuit_meta.into(),
        &cert,
        now,
        &authority_key_id,
        &issuer_pk_x,
        &issuer_pk_y,
        &prev_cmt_x,
        &prev_cmt_y,
        &prev_cmt_r,
    )
    .map_err(|e| MoproError::NoirError(e.to_string()))?;

    Ok(proof.into())
}

